import CoreGraphics

/// Corner-radius tokens from the web design system.
enum AppRadius {
    /// 14 pt — buttons, text fields, small elements (`--ui-radius-sm`)
    static let small:  CGFloat = 14
    /// 16 pt — standard cards (`--ui-radius-md`)
    static let medium: CGFloat = 16
    /// 20 pt — sheets, modals, hero cards (`--ui-radius-lg`)
    static let large:  CGFloat = 20
}
